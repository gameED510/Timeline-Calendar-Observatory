insert into public.timeline_projects (user_id, project_id, project, version, deleted, updated_at, created_at)
select td.user_id,
       item ->> 'id',
       item,
       1,
       false,
       td.updated_at,
       td.created_at
from public.timeline_data as td
cross join lateral jsonb_array_elements(td.projects) as item
where jsonb_typeof(td.projects) = 'array'
  and jsonb_typeof(item) = 'object'
  and coalesce(item ->> 'id', '') <> ''
on conflict (user_id, project_id) do nothing;

insert into public.timeline_snapshots (user_id, projects, reason, created_at)
select td.user_id, td.projects, 'migration', td.updated_at
from public.timeline_data as td
where jsonb_typeof(td.projects) = 'array'
  and not exists (
    select 1 from public.timeline_snapshots as ts where ts.user_id = td.user_id
  );
